#!/usr/bin/env python3
"""bin2h.py <file> <out.h> <name>: a file as a C byte array (for the module's demo build)."""
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/bin2h.py -- do not edit.\n#pragma once\n#include <stdint.h>\n")
    f.write("static const uint8_t %s[%d] = {\n" % (sys.argv[3], len(data)))
    for i in range(0, len(data), 24):
        f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
