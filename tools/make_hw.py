#!/usr/bin/env python3
"""Meshtastic's HardwareModel enum -> common/hwmodels.h (display names by number).

    pip install --target <dir> --no-deps meshtastic protobuf   (then empty meshtastic/__init__.py there)
    PYTHONPATH=<dir> python3 make_hw.py
"""
import os
from meshtastic.protobuf import mesh_pb2

SPECIAL = {"TBEAM": "T-Beam", "TLORA": "T-LoRa", "T_ECHO": "T-Echo", "T_DECK": "T-Deck", "T_WATCH": "T-Watch",
           "HELTEC": "Heltec", "RAK": "RAK", "LILYGO": "LilyGO", "STATION": "Station", "NANO": "Nano", "SEEED": "Seeed",
           "PORTDUINO": "Linux (Portduino)", "PRIVATE_HW": "Private hardware", "UNSET": "Unknown"}


def pretty(n):
    if n in SPECIAL:
        return SPECIAL[n]
    words = []
    for w in n.split("_"):
        if w in SPECIAL:
            words.append(SPECIAL[w])
        elif any(c.isdigit() for c in w) or len(w) <= 3:
            words.append(w)
        else:
            words.append(w.capitalize())
    return " ".join(words).replace("T Beam", "T-Beam").replace("T Echo", "T-Echo").replace("T Deck", "T-Deck")


def main():
    enum = mesh_pb2.HardwareModel
    top = max(enum.values())
    names = {v: pretty(k) for k, v in enum.items()}
    out = os.path.join(os.path.dirname(__file__), "..", "common", "hwmodels.h")
    with open(out, "w") as f:
        f.write("// Generated by tools/make_hw.py from Meshtastic's HardwareModel enum -- do not edit.\n#pragma once\n\n")
        f.write("static const char *lp_hw_name(unsigned m)\n{\n    switch (m) {\n")
        for v in sorted(names):
            f.write('    case %d: return "%s";\n' % (v, names[v][:22]))
        f.write('    default: return "Other";\n    }\n}\n')
    print(out, len(names), "models, highest", top)


if __name__ == "__main__":
    main()
